import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {routeInventory} from './contract-inventory.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const routes=routeInventory();
const content='// Generated by scripts/generate-contract-inventory.mjs. Review route semantics separately.\nexport const mountedOperations = '+JSON.stringify(routes,null,2)+';\n';
const target=path.join(root,'src/docs/mounted-operations.ts');
if(process.argv.includes('--check')) {
  if(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==content) throw new Error('Mounted route inventory is stale. Regenerate it.');
} else fs.writeFileSync(target,content);
